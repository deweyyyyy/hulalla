        let currentScene = 'start';
        let choicesMade = [];
        let bgMusicEnabled = true;
        let sfxEnabled = true;
        let soundsInitialized = false;
        
        function showSoundSettings() {
            document.getElementById('startScreen').style.display = 'none';
            document.getElementById('soundSettings').style.display = 'flex';
        }
        
        function startStoryWithSettings(skipSound = false) {
            if (skipSound) {
                bgMusicEnabled = false;
                sfxEnabled = false;
            } else {
                bgMusicEnabled = document.getElementById('bgMusicToggle').checked;
                sfxEnabled = document.getElementById('sfxToggle').checked;
            }
            
            document.getElementById('soundSettings').style.display = 'none';
            document.getElementById('storySection').classList.add('active');
            document.getElementById('soundControl').style.display = 'flex';
            
            if (bgMusicEnabled) {
                const bgMusic = document.getElementById('bgMusic');
                bgMusic.volume = 0.3;
                bgMusic.play().catch(() => {});
            }
            
            soundsInitialized = true;
            showScene('start');
        }
        
        function toggleAllSound() {
            const bgMusic = document.getElementById('bgMusic');
            const icon = document.getElementById('soundIcon');
            
            if (bgMusic.paused && bgMusicEnabled) {
                bgMusic.play().catch(() => {});
                icon.className = 'fas fa-volume-up';
            } else {
                bgMusic.pause();
                icon.className = 'fas fa-volume-mute';
            }
        }
        
        function playSound(soundId) {
            if (!sfxEnabled || !soundsInitialized) return;
            
            const sound = document.getElementById(soundId);
            if (sound) {
                sound.currentTime = 0;
                sound.volume = 0.5;
                // Silently fail if sound file doesn't exist
                sound.play().catch(() => {
                    console.log('Sound not available:', soundId);
                });
            }
        }
        
        function startStory() {
            document.getElementById('startScreen').classList.add('hidden');
            document.getElementById('storySection').classList.add('active');
            showScene('start');
        }
        
        function showScene(sceneId) {
            const scene = story[sceneId];
            
            // Error handling - if scene doesn't exist, show a fallback
            if (!scene) {
                console.error('Scene not found:', sceneId);
                // Show a generic ending instead of crashing
                showEnding({
                    type: "bad",
                    title: "ERROR ENDING",
                    subtitle: "ทางตัน",
                    emoji: "❓",
                    text: "คุณหลงทางในโรงเรียน... ไม่มีใครพบคุณอีกเลย",
                    bravery: "0%"
                });
                return;
            }
            
            currentScene = sceneId;
            
            // Play appropriate sound effects
            if (scene.sound) {
                playSound(scene.sound);
            }
            
            // Apply effects
            if (scene.effect === 'shake') {
                document.getElementById('mainContainer').classList.add('shake');
                playSound('sfxScream');
                setTimeout(() => {
                    document.getElementById('mainContainer').classList.remove('shake');
                }, 500);
            } else if (scene.effect === 'jumpscare') {
                showJumpscare();
            } else if (scene.effect === 'flicker') {
                document.getElementById('mainContainer').classList.add('flicker');
                setTimeout(() => {
                    document.getElementById('mainContainer').classList.remove('flicker');
                }, 1000);
            }
            
            // Check if ending
            if (scene.ending) {
                const bgMusic = document.getElementById('bgMusic');
                bgMusic.pause();
                setTimeout(() => showEnding(scene.ending), 500);
                return;
            }
            
            // Update scene
            document.getElementById('sceneEmoji').textContent = scene.emoji;
            document.getElementById('chapterBadge').textContent = scene.chapter;
            document.getElementById('storyText').textContent = scene.text;
            
            // Update choices
            const choicesContainer = document.getElementById('choices');
            choicesContainer.innerHTML = '';
            
            scene.choices.forEach(choice => {
                const btn = document.createElement('button');
                btn.className = 'choice-btn';
                btn.innerHTML = `<i class="fas ${choice.icon}"></i> ${choice.text}`;
                btn.onclick = () => {
                    choicesMade.push(choice.text);
                    showScene(choice.next);
                };
                choicesContainer.appendChild(btn);
            });
            
            // Scroll to top
            window.scrollTo(0, 0);
        }
        
        function showJumpscare() {
            const overlay = document.getElementById('jumpscareOverlay');
            const faces = ['👹', '😱', '💀', '👻', '🎃'];
            document.getElementById('jumpscareContent').textContent = faces[Math.floor(Math.random() * faces.length)];
            
            overlay.classList.add('show');
            playSound('sfxScream');
            
            // Vibrate if supported
            if (navigator.vibrate) {
                navigator.vibrate([100, 50, 100]);
            }
            
            setTimeout(() => {
                overlay.classList.remove('show');
            }, 500);
        }
        
        function showEnding(ending) {
            document.getElementById('storySection').classList.remove('active');
            document.getElementById('endingScreen').classList.add('active');
            
            document.getElementById('endingEmoji').textContent = ending.emoji;
            document.getElementById('endingTitle').textContent = ending.title;
            document.getElementById('endingTitle').className = `ending-title ${ending.type}`;
            document.getElementById('endingSubtitle').textContent = ending.subtitle;
            document.getElementById('endingText').textContent = ending.text;
            document.getElementById('endingType').textContent = ending.type === 'good' ? 'Good Ending' : ending.type === 'bad' ? 'Bad Ending' : 'Neutral Ending';
            document.getElementById('braveryScore').textContent = ending.bravery;
        }
        
